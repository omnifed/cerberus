import { mkdir } from 'node:fs/promises'
import { join } from 'node:path'
import { COMPONENTS, type ComponentConfig } from './manifest'

const GENERATED_HEADER = `/**\n * @generated by Cerberus CLI\n * This file is auto-generated based on the Ark UI anatomy. \n * Do not edit this file manually.\n */\n\n`

const REF_URL = 'https://cerberus.digitalu.design/docs/components'

async function generateComponentAPI(config: ComponentConfig) {
  const { name, key, anatomy, description, abstractions = [] } = config

  const outputDir = join(process.cwd(), 'src', 'components', key)

  await mkdir(outputDir, { recursive: true })
  const parts = anatomy.keys() as string[]

  // --- 1. Generate primitives.tsx ---
  let primitivesCode = GENERATED_HEADER + `'use client'\n\n`
  primitivesCode += `import { ${name} as Ark${name} } from '@ark-ui/react/${key}'\n`
  primitivesCode += `import { type ComponentProps, createSlotRecipeContext } from 'styled-system/jsx'\n`
  primitivesCode += `import { ${key} } from 'styled-system/recipes'\n\n`
  primitivesCode += `const { withProvider, withContext } = createSlotRecipeContext(${key})\n\n`

  parts.forEach((part) => {
    const isRoot = part === 'root'
    const partName = `${name}${part.charAt(0).toUpperCase() + part.slice(1)}`
    const arkPart = `Ark${name}.${part.charAt(0).toUpperCase() + part.slice(1)}`

    primitivesCode += `// ${partName} -----------------------------------------------------\n\n`
    primitivesCode += `export type ${partName}Props = ComponentProps<typeof ${partName}>\n`
    primitivesCode += `export const ${partName} = ${isRoot ? 'withProvider' : 'withContext'}(${arkPart}, '${part}')\n\n`
  })

  // --- 2. Generate api.ts ---
  let apiCode = GENERATED_HEADER

  // Import custom abstractions
  abstractions.forEach((abs) => {
    apiCode += `import { ${name}${abs.name} } from './${abs.file}'\n`
  })

  // Import primitives
  apiCode += `import {\n`
  parts.forEach((part) => {
    const partName = `${name}${part.charAt(0).toUpperCase() + part.slice(1)}`
    apiCode += `  ${partName},\n`
  })
  apiCode += `} from './primitives'\n\n`

  // --- Generate Rust-Style JSDoc ---
  let jsDoc = `/**\n`
  jsDoc += ` * ## ${name}\n * \n`

  // Format the description to have the JSDoc '*' prefix on new lines
  const formattedDesc = description.split('\n').join('\n * ')
  jsDoc += ` * ${formattedDesc}\n * \n`
  jsDoc += ` * For a customizable ${name}, use style props, slots, or the base-level primitives for granular control over the component's structure and behavior.`

  jsDoc += ` * ## Slots\n * \n`
  jsDoc += ` * | Slot | Description |\n`
  jsDoc += ` * |------|-------------|\n`

  // Auto-generate the Primitive Slots
  parts.forEach((part) => {
    const exportKey =
      part === 'root' ? 'Root' : part.charAt(0).toUpperCase() + part.slice(1)
    const desc =
      part === 'root'
        ? `The root element of the ${name} component.`
        : `The ${part} element of the ${name} component.`
    jsDoc += ` * | \`${exportKey}\` | ${desc} |\n`
  })

  // Auto-generate the Abstraction Slots
  abstractions.forEach((abs) => {
    jsDoc += ` * | \`${abs.name}\` | ${abs.description} |\n`
  })

  jsDoc += ` * \n`
  jsDoc += ` * ## Reference\n`
  jsDoc += ` * @see [${name} Docs](${REF_URL}/${key})\n`
  jsDoc += ` */\n`

  apiCode += jsDoc
  apiCode += `export const ${name} = Object.assign(${name}Root, {\n`
  parts.forEach((part) => {
    const isRoot = part === 'root'
    const exportKey = isRoot ? 'Root' : part.charAt(0).toUpperCase() + part.slice(1)
    const partName = `${name}${part.charAt(0).toUpperCase() + part.slice(1)}`
    apiCode += `  ${exportKey}: ${partName},\n`
  })
  abstractions.forEach((abs) => {
    apiCode += `  ${abs.name}: ${name}${abs.name},\n`
  })
  apiCode += `})\n`

  // --- 3. Write files ---
  await Bun.write(join(outputDir, 'primitives.tsx'), primitivesCode)
  await Bun.write(join(outputDir, 'api.ts'), apiCode)
  await Bun.write(
    join(outputDir, 'index.ts'),
    `${GENERATED_HEADER}export * from './api'\n`,
  )

  console.log(`✅ Generated ${name} API at ${outputDir}`)
}

async function run() {
  console.log('Generating Cerberus APIs...\n')
  for (const config of COMPONENTS) {
    await generateComponentAPI(config)
  }
  console.log('🎉 All APIs generated successfully!')
}

run().catch(console.error)
