import { join, relative } from 'node:path'
import { z } from 'zod'
import type { GeneratedFile } from '../core/emit'
import { CODEGEN_ROOT, DOCS_SPEC_OUT_DIR } from '../core/paths'
import { renderDigest, renderLlmsIndex } from './digest'
import { ComponentDocSpecSchema } from './schema'
import type { ComponentDocSpec } from './types'

export const SCHEMA_FILE_NAME = 'component-doc-spec.schema.json'

export function specJsonFile(spec: ComponentDocSpec): GeneratedFile {
  return {
    path: join(DOCS_SPEC_OUT_DIR, `${spec.key}.json`),
    content: `${JSON.stringify(spec, null, 2)}\n`,
  }
}

/** `index.ts` mapping each component key to its imported JSON spec. */
export function barrelFile(keys: string[]): GeneratedFile {
  // A Bun-free module, so the docs app can type-check against it
  const typesImport = relative(
    DOCS_SPEC_OUT_DIR,
    join(CODEGEN_ROOT, 'docs', 'types'),
  )
  const varName = (key: string) => `${key.replace(/-/g, '_')}Spec`

  const lines = [
    `// @generated by Cerberus CLI — Do not edit manually.`,
    `import type { ComponentDocSpec } from '${typesImport}'`,
    ...keys.map((key) => `import ${varName(key)} from './${key}.json'`),
    ``,
    `export const API_SPECS: Record<string, ComponentDocSpec> = {`,
    ...keys.map((key) => `  '${key}': ${varName(key)} as ComponentDocSpec,`),
    `}`,
    ``,
  ]
  return {
    path: join(DOCS_SPEC_OUT_DIR, 'index.ts'),
    content: lines.join('\n'),
  }
}

/** JSON Schema for the spec files, for editors, CI and agents. */
export function schemaFile(): GeneratedFile {
  const schema = z.toJSONSchema(ComponentDocSpecSchema, {
    target: 'draft-2020-12',
  })
  return {
    path: join(DOCS_SPEC_OUT_DIR, SCHEMA_FILE_NAME),
    content: `${JSON.stringify({ title: 'ComponentDocSpec', ...schema }, null, 2)}\n`,
  }
}

/** Markdown API reference for one component, next to its JSON. */
export function digestFile(spec: ComponentDocSpec): GeneratedFile {
  return {
    path: join(DOCS_SPEC_OUT_DIR, `${spec.key}.md`),
    content: renderDigest(spec),
  }
}

/** `llms.txt` index of the digests. */
export function llmsIndexFile(specs: ComponentDocSpec[]): GeneratedFile {
  return {
    path: join(DOCS_SPEC_OUT_DIR, 'llms.txt'),
    content: renderLlmsIndex(specs),
  }
}
